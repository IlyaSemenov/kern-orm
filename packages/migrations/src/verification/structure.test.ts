import { expect, it } from "bun:test"

import * as t from "kern-orm/types"

import { describePostgres } from "../../testing/postgres"
import { describeHelperSchema, helperSchema, inHelperSchema } from "../helpers/testing"

describePostgres("describeSchema", ({ database, testTransaction }) => {
  /** Runs `script` in schema `migrations_helpers` and describes the schema. */
  const describeScript = (script: string) =>
    testTransaction(() =>
      inHelperSchema(database, async () => {
        await database.script(script)
        return await describeHelperSchema(database)
      }),
    )

  it("describes each object of the schema on a line, in the order of bytes", async () => {
    const lines = await describeScript(`
      CREATE TYPE status AS ENUM ('draft', 'published');
      CREATE DOMAIN positive AS integer NOT NULL DEFAULT 1 CONSTRAINT positive_check CHECK (VALUE > 0);
      CREATE TYPE point2 AS (x integer, y integer);
      CREATE TYPE span AS RANGE (subtype = integer);
      CREATE TABLE form (
        id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        status status NOT NULL DEFAULT 'draft',
        slug text COLLATE "C",
        position positive,
        total integer GENERATED ALWAYS AS (id * 2) STORED,
        number serial,
        body text
      ) WITH (fillfactor = 70);
      ALTER TABLE form
        ALTER COLUMN body SET STORAGE EXTERNAL,
        ALTER COLUMN body SET COMPRESSION pglz,
        ALTER COLUMN body SET STATISTICS 500;
      CREATE INDEX form_slug_idx ON form (slug) WHERE slug IS NOT NULL;
      CREATE SEQUENCE ticket_seq START 10;
      CREATE VIEW published_form AS SELECT id FROM form WHERE status = 'published';
      ALTER VIEW published_form ALTER COLUMN id SET DEFAULT 5;
      CREATE FUNCTION touch() RETURNS trigger LANGUAGE plpgsql AS $$BEGIN RETURN NEW; END$$;
      CREATE TRIGGER form_touch BEFORE UPDATE ON form FOR EACH ROW EXECUTE FUNCTION touch();
      ALTER TABLE form ENABLE ALWAYS TRIGGER form_touch;
      ALTER TABLE form ENABLE ROW LEVEL SECURITY;
      CREATE POLICY form_published ON form FOR SELECT USING (status = 'published');
      CREATE RULE form_log AS ON DELETE TO form DO NOTHING;
      ALTER TABLE form DISABLE RULE form_log;
      CREATE STATISTICS form_stats ON status, slug FROM form;
      CREATE AGGREGATE total_sum(integer) (SFUNC = int4pl, STYPE = integer, INITCOND = '0');
      CREATE TABLE event (id integer, at date) PARTITION BY RANGE (at);
      CREATE TABLE event_2026 PARTITION OF event FOR VALUES FROM ('2026-01-01') TO ('2027-01-01');
      CREATE UNLOGGED TABLE cache (key text);
      ALTER TABLE cache REPLICA IDENTITY FULL;
    `)

    expect(lines).toEqual([
      "aggregate total_sum(integer) (SFUNC = int4pl, STYPE = integer, INITCOND = '0')",
      "attribute point2.x integer",
      "attribute point2.y integer",
      "column cache.key text",
      "column event.at date",
      "column event.id integer",
      "column event_2026.at date",
      "column event_2026.id integer",
      "column form.body text STORAGE EXTERNAL COMPRESSION pglz STATISTICS 500",
      "column form.id integer NOT NULL GENERATED BY DEFAULT AS IDENTITY",
      "column form.number integer NOT NULL DEFAULT nextval('form_number_seq'::regclass)",
      "column form.position positive",
      'column form.slug text COLLATE "C"',
      "column form.status status NOT NULL DEFAULT 'draft'::status",
      "column form.total integer GENERATED ALWAYS AS ((id * 2)) STORED",
      "column published_form.id integer DEFAULT 5",
      "constraint form.form_pkey PRIMARY KEY (id)",
      "constraint positive.positive_check CHECK ((VALUE > 0))",
      "function CREATE OR REPLACE FUNCTION migrations_helpers.touch()\n RETURNS trigger\n LANGUAGE plpgsql\nAS $function$BEGIN RETURN NEW; END$function$",
      "index CREATE INDEX form_slug_idx ON migrations_helpers.form USING btree (slug) WHERE (slug IS NOT NULL)",
      "index CREATE UNIQUE INDEX form_pkey ON migrations_helpers.form USING btree (id)",
      "policy form.form_published AS PERMISSIVE FOR SELECT TO public USING ((status = 'published'::status))",
      "rule CREATE RULE form_log AS\n    ON DELETE TO migrations_helpers.form DO NOTHING; DISABLED",
      "sequence form_id_seq AS integer START 1 INCREMENT 1 MINVALUE 1 MAXVALUE 2147483647 CACHE 1 OWNED BY form.id",
      "sequence form_number_seq AS integer START 1 INCREMENT 1 MINVALUE 1 MAXVALUE 2147483647 CACHE 1 OWNED BY form.number",
      "sequence ticket_seq AS bigint START 10 INCREMENT 1 MINVALUE 1 MAXVALUE 9223372036854775807 CACHE 1",
      "statistics CREATE STATISTICS migrations_helpers.form_stats ON status, slug FROM form",
      "table cache UNLOGGED REPLICA IDENTITY FULL",
      "table event PARTITION BY RANGE (at)",
      "table event_2026 PARTITION OF event FOR VALUES FROM ('2026-01-01') TO ('2027-01-01')",
      "table form WITH (fillfactor=70) ROW LEVEL SECURITY",
      "trigger CREATE TRIGGER form_touch BEFORE UPDATE ON migrations_helpers.form FOR EACH ROW EXECUTE FUNCTION touch() ENABLE ALWAYS",
      "type point2 COMPOSITE",
      "type positive DOMAIN integer NOT NULL DEFAULT 1",
      "type span RANGE (SUBTYPE = integer)",
      "type status ENUM ('draft', 'published')",
      "view published_form SELECT id\n   FROM form\n  WHERE (status = 'published'::status);",
    ])
  })

  it("describes a collation by its properties", async () => {
    const lines = await describeScript(
      "CREATE COLLATION ci (provider = icu, locale = 'und-u-ks-level2', deterministic = false)",
    )

    expect(lines).toEqual([
      expect.stringMatching(
        /^collation ci \{.*"colllocale": "und-u-ks-level2".*"collprovider": "i", "collisdeterministic": false\}$/,
      ),
    ])
  })

  it("describes a table created again with its columns in another order as before", async () => {
    const lines = await testTransaction(() =>
      inHelperSchema(database, async () => {
        await database.script(
          "CREATE TABLE form (id integer PRIMARY KEY, slug text NOT NULL DEFAULT '')",
        )
        const before = await describeHelperSchema(database)
        await database.script(`
          DROP TABLE form;
          CREATE TABLE form (slug text NOT NULL DEFAULT '', id integer PRIMARY KEY);
        `)
        return { before, after: await describeHelperSchema(database) }
      }),
    )

    expect(lines.after).toEqual(lines.before)
  })

  it("describes the options of a table in the order of their names, which a rollback of a change of one of them keeps", async () => {
    const lines = await testTransaction(() =>
      inHelperSchema(database, async () => {
        await database.script(
          "CREATE TABLE form (id integer) WITH (fillfactor = 70, autovacuum_enabled = false)",
        )
        const before = await describeHelperSchema(database)
        await database.script(`
          ALTER TABLE form SET (fillfactor = 80);
          ALTER TABLE form SET (fillfactor = 70);
        `)
        return { before, after: await describeHelperSchema(database) }
      }),
    )

    expect(lines.before).toContain("table form WITH (autovacuum_enabled=false, fillfactor=70)")
    expect(lines.after).toEqual(lines.before)
  })

  it("leaves out the objects of extensions, including their composite types", async () => {
    const lines = await describeScript(`
      CREATE EXTENSION citext SCHEMA ${helperSchema};
      CREATE EXTENSION dblink SCHEMA ${helperSchema};
      CREATE TABLE app_user (email citext);
    `)

    expect(lines).toEqual(["column app_user.email citext", "table app_user"])
  })

  it("shows the owners other than the role that describes the schema", async () => {
    const lines = await describeScript(`
      CREATE TABLE form (id integer);
      CREATE FUNCTION form_count() RETURNS bigint LANGUAGE sql SECURITY DEFINER AS 'SELECT count(*) FROM form';
      ALTER TABLE form OWNER TO pg_database_owner;
      ALTER FUNCTION form_count() OWNER TO pg_database_owner;
    `)

    expect(lines).toEqual([
      "column form.id integer",
      "function CREATE OR REPLACE FUNCTION migrations_helpers.form_count()\n RETURNS bigint\n LANGUAGE sql\n SECURITY DEFINER\nAS $function$SELECT count(*) FROM form$function$ OWNER pg_database_owner",
      "table form OWNER pg_database_owner",
    ])
  })

  it("shows the privileges that differ from the default ones, such as an ACL that grants nothing, whatever the order of grants and revokes", async () => {
    const result = await testTransaction(() =>
      inHelperSchema(database, async () => {
        await database.script(`
          CREATE TABLE form (id integer, slug text);
          CREATE TABLE tag (id integer);
          CREATE FUNCTION form_count() RETURNS bigint LANGUAGE sql AS 'SELECT count(*) FROM form';
          CREATE FUNCTION tag_count() RETURNS bigint LANGUAGE sql AS 'SELECT count(*) FROM tag';
          CREATE FUNCTION answer() RETURNS integer LANGUAGE sql AS 'SELECT 42';
          GRANT SELECT ON form TO PUBLIC;
          GRANT UPDATE (slug) ON form TO PUBLIC;
          REVOKE EXECUTE ON FUNCTION form_count() FROM PUBLIC;
          GRANT SELECT ON tag TO PUBLIC;
          REVOKE SELECT ON tag FROM PUBLIC;
          REVOKE EXECUTE ON FUNCTION tag_count() FROM PUBLIC;
          GRANT EXECUTE ON FUNCTION tag_count() TO PUBLIC;
          GRANT UPDATE (id) ON tag TO PUBLIC;
          REVOKE UPDATE (id) ON tag FROM PUBLIC;
          REVOKE ALL ON FUNCTION answer() FROM PUBLIC, CURRENT_USER;
        `)
        return {
          user: await database.query`SELECT current_user::text`.get(t.text),
          lines: await describeHelperSchema(database),
        }
      }),
    )

    const { user } = result
    expect(result.lines).toEqual([
      "column form.id integer",
      `column form.slug text GRANT {=w/${user}}`,
      "column tag.id integer",
      "function CREATE OR REPLACE FUNCTION migrations_helpers.answer()\n RETURNS integer\n LANGUAGE sql\nAS $function$SELECT 42$function$ GRANT {}",
      `function CREATE OR REPLACE FUNCTION migrations_helpers.form_count()\n RETURNS bigint\n LANGUAGE sql\nAS $function$SELECT count(*) FROM form$function$ GRANT {${user}=X/${user}}`,
      "function CREATE OR REPLACE FUNCTION migrations_helpers.tag_count()\n RETURNS bigint\n LANGUAGE sql\nAS $function$SELECT count(*) FROM tag$function$",
      `table form GRANT {=r/${user},${user}=arwdDxtm/${user}}`,
      "table tag",
    ])
  })
})
