import { expect, it } from "bun:test"

import { describePostgres } from "../../testing/postgres"
import { bindSchema } from "../execution/db"
import { one } from "../schema/relation"
import { defineSchema } from "../schema/schema"
import { toSnakeCase } from "../table/snake-case"
import { createTableFactory, defineTable } from "../table/table"
import { defineType } from "../type/type"
import * as t from "../types"

import { findTableMismatches } from "./tables"

describePostgres("findTableMismatches", ({ database, testTransaction }) => {
  const defineSnakeTable = createTableFactory({ columnName: toSnakeCase })

  const user = defineSnakeTable("user", {
    id: t.uuid.primaryKey().hasDefault(),
    createdAt: t.timestamptz.hasDefault(),
    email: t.varchar.with(255).unique(),
    lastLoginAt: t.timestamptz.nullable(),
  })

  const form = defineSnakeTable("form", {
    id: t.integer.primaryKey().hasDefault(),
    authorId: t.uuid,
    name: t.text,
  })

  const field = defineSnakeTable(
    "form_field",
    {
      id: t.integer.primaryKey().hasDefault(),
      formId: t.integer,
      position: t.integer,
    },
    { unique: [["formId", "position"]] },
  )

  const settings = defineSnakeTable(
    "settings",
    {
      theme: t.text,
    },
    { singleton: true },
  )

  const schema = defineSchema({ user, form, field, settings }).$relations({
    form: {
      author: one(user, { from: "authorId", to: "id", required: true }),
    },
    field: {
      form: one(form, { from: "formId", to: "id", required: true }),
    },
  })

  const db = bindSchema(schema, database)

  const createTables = () =>
    database.script(`
      CREATE TABLE "user" (
        id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
        created_at timestamptz NOT NULL DEFAULT now(),
        email character varying(255) NOT NULL UNIQUE,
        last_login_at timestamptz
      );
      CREATE TABLE form (
        id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
        author_id uuid NOT NULL REFERENCES "user",
        name text NOT NULL
      );
      CREATE TABLE form_field (
        id int4 PRIMARY KEY GENERATED ALWAYS AS IDENTITY,
        form_id integer NOT NULL REFERENCES form,
        position integer NOT NULL,
        UNIQUE (position, form_id)
      );
      CREATE TABLE settings (theme text NOT NULL);
      CREATE UNIQUE INDEX settings_singleton ON settings ((true));
    `)

  it("finds no mismatches of tables that match the database", () =>
    testTransaction(async () => {
      await createTables()

      expect(await findTableMismatches(db)).toEqual([])
    }))

  it("checks the tables in the PostgreSQL schema of the Db", () =>
    testTransaction(async () => {
      await database.script(`
        CREATE SCHEMA tenant;
        SET LOCAL search_path = tenant;
      `)
      await createTables()
      await database.script("SET LOCAL search_path = public")

      expect(
        await findTableMismatches(bindSchema(schema, database, { schemaName: "tenant" })),
      ).toEqual([])
      expect(await findTableMismatches(db)).toEqual([
        { table: "user", message: 'Table "user" does not exist in schema "public"' },
        { table: "form", message: 'Table "form" does not exist in schema "public"' },
        { table: "field", message: 'Table "form_field" does not exist in schema "public"' },
        { table: "settings", message: 'Table "settings" does not exist in schema "public"' },
      ])
    }))

  it("finds a relation of another kind under the name of a table", () =>
    testTransaction(async () => {
      await database.script("CREATE SEQUENCE item")
      const item = defineTable("item", {
        id: t.integer,
      })

      expect(await findTableMismatches(bindSchema(defineSchema({ item }), database))).toEqual([
        { table: "item", message: '"item" in schema "public" is not a table or a view' },
      ])
    }))

  it("finds missing columns and columns of other types by their physical names", () =>
    testTransaction(async () => {
      await database.script(`
        CREATE DOMAIN email AS text;
        CREATE TABLE item (
          title varchar(100) NOT NULL,
          price numeric(10, 2) NOT NULL,
          address email NOT NULL,
          tags text[] NOT NULL
        );
      `)
      const item = defineSnakeTable("item", {
        title: t.varchar.with(255),
        price: t.numeric.with(10, 2),
        address: t.text,
        tags: t.array(t.text),
        createdAt: t.timestamptz,
        code: defineType({ sqlType: "item_code" }),
      })

      expect(await findTableMismatches(bindSchema(defineSchema({ item }), database))).toEqual([
        {
          table: "item",
          message:
            'Column "title" is of type character varying(100) rather than character varying(255)',
        },
        { table: "item", message: 'Column "address" is of type email rather than text' },
        { table: "item", message: 'Column "createdAt" (created_at) does not exist' },
        { table: "item", message: 'Column "code" does not exist' },
      ])
    }))

  it("finds a column whose SQL type does not exist", () =>
    testTransaction(async () => {
      await database.script("CREATE TABLE item (code text NOT NULL)")
      const item = defineTable("item", {
        code: defineType({ sqlType: "item_code" }),
      })

      expect(await findTableMismatches(bindSchema(defineSchema({ item }), database))).toEqual([
        { table: "item", message: 'Column "code" is of type "item_code", which does not exist' },
      ])
    }))

  it("finds mismatches of nullability, also of a NOT VALID not-null constraint", () =>
    testTransaction(async () => {
      await database.script(`
        CREATE TABLE item (title text, note text NOT NULL, code text, comment text);
        ALTER TABLE item ADD CONSTRAINT item_code_not_null NOT NULL code NOT VALID;
        ALTER TABLE item ADD CONSTRAINT item_comment_not_null NOT NULL comment NOT VALID;
      `)
      const item = defineTable("item", {
        title: t.text,
        note: t.text.nullable(),
        code: t.text,
        comment: t.text.nullable(),
      })

      expect(await findTableMismatches(bindSchema(defineSchema({ item }), database))).toEqual([
        {
          table: "item",
          message: 'Column "title" is nullable, but the table defines it as not nullable',
        },
        {
          table: "item",
          message: 'Column "note" is NOT NULL, but the table defines it as nullable',
        },
        {
          table: "item",
          message:
            'Column "code" has a NOT VALID not-null constraint, so existing rows may hold NULL, but the table defines it as not nullable',
        },
        {
          table: "item",
          message: 'Column "comment" is NOT NULL, but the table defines it as nullable',
        },
      ])
    }))

  it("finds a column marked with hasDefault() without a default, an identity, or a generated value", () =>
    testTransaction(async () => {
      await database.script(`
        CREATE TABLE item (
          id integer PRIMARY KEY GENERATED ALWAYS AS IDENTITY,
          price integer NOT NULL,
          total integer GENERATED ALWAYS AS (price * 2) STORED,
          created_at timestamptz NOT NULL DEFAULT now(),
          updated_at timestamptz NOT NULL
        )
      `)
      const item = defineSnakeTable("item", {
        id: t.integer.primaryKey().hasDefault(),
        price: t.integer,
        total: t.integer.nullable().hasDefault(),
        createdAt: t.timestamptz,
        updatedAt: t.timestamptz.hasDefault(),
      })

      expect(await findTableMismatches(bindSchema(defineSchema({ item }), database))).toEqual([
        {
          table: "item",
          message:
            'Column "updatedAt" (updated_at) has no default, but the table marks it with hasDefault()',
        },
      ])
    }))

  it("finds a column that the table does not define and that every insert must give", () =>
    testTransaction(async () => {
      await database.script(`
        CREATE TABLE item (
          title text NOT NULL,
          note text,
          created_at timestamptz NOT NULL DEFAULT now(),
          code text NOT NULL,
          legacy text
        );
        ALTER TABLE item ADD CONSTRAINT item_legacy_not_null NOT NULL legacy NOT VALID;
      `)
      const item = defineTable("item", {
        title: t.text,
      })

      expect(await findTableMismatches(bindSchema(defineSchema({ item }), database))).toEqual([
        {
          table: "item",
          message:
            'Column "code" is NOT NULL without a default, so every insert of the table, which does not define it, fails',
        },
        {
          table: "item",
          message:
            'Column "legacy" is NOT NULL without a default, so every insert of the table, which does not define it, fails',
        },
      ])
    }))

  it("checks each column key mapped to the same physical column", () =>
    testTransaction(async () => {
      await database.script("CREATE TABLE item (title text)")
      const item = defineTable("item", {
        title: t.text.nullable(),
        heading: t.text.columnName("title"),
      })

      expect(await findTableMismatches(bindSchema(defineSchema({ item }), database))).toEqual([
        {
          table: "item",
          message: 'Column "heading" (title) is nullable, but the table defines it as not nullable',
        },
      ])
    }))

  it("finds keys without a unique index that ON CONFLICT of their columns infers, or with a deferrable one", () =>
    testTransaction(async () => {
      await database.script(`
        CREATE TABLE item (
          id integer NOT NULL,
          code text NOT NULL,
          slug text NOT NULL,
          group_id integer NOT NULL,
          position integer NOT NULL,
          email text NOT NULL,
          number integer NOT NULL,
          reference text NOT NULL,
          CONSTRAINT item_code_key UNIQUE (code) DEFERRABLE INITIALLY IMMEDIATE,
          CONSTRAINT item_number_deferrable_key UNIQUE (number) DEFERRABLE
        );
        CREATE UNIQUE INDEX item_number_key ON item (number);
        CREATE UNIQUE INDEX item_reference_key ON item (reference, reference);
        CREATE UNIQUE INDEX item_slug_key ON item (slug) WHERE slug <> '';
        CREATE UNIQUE INDEX item_group_position_key ON item (position, group_id) INCLUDE (email);
        CREATE UNIQUE INDEX item_email_key ON item (lower(email));
      `)
      const item = defineSnakeTable(
        "item",
        {
          id: t.integer.primaryKey(),
          code: t.text.unique(),
          slug: t.text.unique(),
          groupId: t.integer,
          position: t.integer,
          email: t.text.unique(),
          number: t.integer.unique(),
          reference: t.text.unique(),
        },
        { unique: [["groupId", "position"]] },
      )

      expect(await findTableMismatches(bindSchema(defineSchema({ item }), database))).toEqual([
        { table: "item", message: "Primary key (id) has no unique index" },
        {
          table: "item",
          message:
            'Unique key (code) has deferrable unique index "item_code_key", which ON CONFLICT rejects as an arbiter',
        },
        {
          table: "item",
          message: 'Unique key (slug) has no usable unique index: "item_slug_key" is partial',
        },
        { table: "item", message: "Unique key (email) has no unique index" },
        {
          table: "item",
          message:
            'Unique key (number) has deferrable unique index "item_number_deferrable_key", which ON CONFLICT rejects as an arbiter',
        },
      ])
    }))

  it("finds a singleton table without a unique index of (true)", () =>
    testTransaction(async () => {
      await database.script(`
        CREATE TABLE settings (theme text NOT NULL);
        CREATE UNIQUE INDEX settings_theme_key ON settings ((true)) WHERE theme <> '';
      `)

      expect(await findTableMismatches(bindSchema(defineSchema({ settings }), database))).toEqual([
        {
          table: "settings",
          message:
            'Singleton table has no usable unique index of (true): "settings_theme_key" is partial',
        },
      ])
    }))

  it("finds required relations without a foreign key of their pairs of columns", () =>
    testTransaction(async () => {
      await database.script(`
        CREATE TABLE parent (a integer NOT NULL, b integer NOT NULL, UNIQUE (a, b));
        CREATE TABLE child (
          id integer NOT NULL,
          x integer NOT NULL,
          y integer NOT NULL,
          FOREIGN KEY (y, x) REFERENCES parent (b, a)
        );
        CREATE TABLE swapped (x integer NOT NULL, y integer NOT NULL, FOREIGN KEY (x, y) REFERENCES parent (b, a));
        CREATE TABLE missing (x integer NOT NULL, y integer NOT NULL);
      `)
      const parent = defineTable(
        "parent",
        {
          a: t.integer,
          b: t.integer,
        },
        { unique: [["a", "b"]] },
      )
      const child = defineTable("child", {
        id: t.integer,
        x: t.integer,
        y: t.integer,
      })
      const swapped = defineTable("swapped", {
        x: t.integer,
        y: t.integer,
      })
      const missing = defineTable("missing", {
        x: t.integer,
        y: t.integer,
      })
      const pairs = { from: ["x", "y"], to: ["a", "b"], required: true } as const
      const relations = defineSchema({ parent, child, swapped, missing }).$relations({
        child: {
          parent: one(parent, pairs),
          optionalParent: one(parent, { from: ["x", "id"], to: ["a", "b"] }),
        },
        swapped: {
          parent: one(parent, pairs),
        },
        missing: {
          parent: one(parent, pairs),
        },
      })

      expect(await findTableMismatches(bindSchema(relations, database))).toEqual([
        {
          table: "swapped",
          message: "Required relation swapped.parent has no foreign key of its columns",
        },
        {
          table: "missing",
          message: "Required relation missing.parent has no foreign key of its columns",
        },
      ])
    }))

  it("finds a required relation whose foreign key is deferrable, not valid, or not enforced", () =>
    testTransaction(async () => {
      await database.script(`
        CREATE TABLE parent (id integer PRIMARY KEY);
        CREATE TABLE deferred (parent_id integer NOT NULL REFERENCES parent DEFERRABLE);
        CREATE TABLE unvalidated (parent_id integer NOT NULL);
        ALTER TABLE unvalidated ADD CONSTRAINT unvalidated_parent_id_fkey FOREIGN KEY (parent_id) REFERENCES parent NOT VALID;
        CREATE TABLE unenforced (parent_id integer NOT NULL REFERENCES parent NOT ENFORCED);
      `)
      const parent = defineTable("parent", {
        id: t.integer.primaryKey(),
      })
      const deferred = defineSnakeTable("deferred", {
        parentId: t.integer,
      })
      const unvalidated = defineSnakeTable("unvalidated", {
        parentId: t.integer,
      })
      const unenforced = defineSnakeTable("unenforced", {
        parentId: t.integer,
      })
      const keys = { from: "parentId", to: "id", required: true } as const
      const relations = defineSchema({ parent, deferred, unvalidated, unenforced }).$relations({
        deferred: {
          parent: one(parent, keys),
        },
        unvalidated: {
          parent: one(parent, keys),
        },
        unenforced: {
          parent: one(parent, keys),
        },
      })

      expect(await findTableMismatches(bindSchema(relations, database))).toEqual([
        {
          table: "deferred",
          message:
            'Required relation deferred.parent has no usable foreign key of its columns: "deferred_parent_id_fkey" is deferrable',
        },
        {
          table: "unvalidated",
          message:
            'Required relation unvalidated.parent has no usable foreign key of its columns: "unvalidated_parent_id_fkey" is not valid',
        },
        {
          table: "unenforced",
          message:
            'Required relation unenforced.parent has no usable foreign key of its columns: "unenforced_parent_id_fkey" is not valid and not enforced',
        },
      ])
    }))

  it("checks only the columns and their types of a view", () =>
    testTransaction(async () => {
      await database.script(`
        CREATE TABLE "user" (id uuid PRIMARY KEY, email text NOT NULL, banned boolean NOT NULL);
        CREATE VIEW active_user AS SELECT id, email FROM "user" WHERE NOT banned;
        CREATE TABLE form (id integer PRIMARY KEY, author_id uuid NOT NULL);
      `)
      const activeUser = defineSnakeTable("active_user", {
        id: t.uuid.primaryKey(),
        email: t.varchar.with(255).hasDefault(),
        name: t.text,
      })
      const authoredForm = defineSnakeTable("form", {
        id: t.integer.primaryKey(),
        authorId: t.uuid,
      })
      const views = defineSchema({ activeUser, authoredForm }).$relations({
        authoredForm: {
          author: one(activeUser, { from: "authorId", to: "id", required: true }),
        },
      })

      expect(await findTableMismatches(bindSchema(views, database))).toEqual([
        {
          table: "activeUser",
          message: 'Column "email" is of type text rather than character varying(255)',
        },
        { table: "activeUser", message: 'Column "name" does not exist' },
      ])
    }))
})
